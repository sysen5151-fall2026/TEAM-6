"""Fix Innoslate Intelligence errors in an EcoCommute XML export. Works on any export that contains the F.x model.
usage: python patch_fix.py in.xml out.xml
"""
import sys, random, string
from lxml import etree

src, dst = sys.argv[1], sys.argv[2]
tree = etree.parse(src); root = tree.getroot()
sch = root.find('schema'); db = root.find('database')
rid = {c.findtext('name'): c.get('id') for c in sch.findall('schemaRelation')}
inv = {c.get('id'): c.findtext('inverseRelationId') for c in sch.findall('schemaRelation')}
rname = {v: k for k, v in rid.items()}
cls = {c.findtext('name'): c.get('id') for c in sch.findall('schemaClass')}
cname = {v: k for k, v in cls.items()}
ents = {e.findtext('globalId'): e for e in db.findall('entity')}
byNum = {}
for g, e in ents.items():
    if e.findtext('number'): byNum[(cname[e.findtext('schemaClassId')], e.findtext('number'))] = g
byName = {(cname[e.findtext('schemaClassId')], e.findtext('name')): g for g, e in ents.items()}
rels = db.findall('relationship')
existing = {(r.findtext('sourceId'), rname[r.findtext('schemaRelationId')], r.findtext('targetId')) for r in rels}
log = []

def setnum(g, n):
    ents[g].find('number').text = n

def add(a, name, b):
    if (a, name, b) in existing: return
    for s, n, t in ((a, name, b), (b, rname[inv[rid[name]]], a)):
        r = etree.SubElement(db, 'relationship')
        etree.SubElement(r, 'sourceId').text = s
        etree.SubElement(r, 'schemaRelationId').text = rid[n]
        etree.SubElement(r, 'targetId').text = t
        existing.add((s, n, t))
    log.append((ents[a].findtext('number') or ents[a].findtext('name'), name, ents[b].findtext('number') or ents[b].findtext('name')))

# 1. Prior-action-depends-on-later-action: Operate Service feeds F.2.4 and F.2.7, so it must come first
if ('Action', 'F.2.8') in byNum:
    g = byNum[('Action', 'F.2.8')]; setnum(g, 'F.2.0'); byNum[('Action', 'F.2.0')] = g
    f2 = byNum[('Action', 'F.2')]; f21 = byNum[('Action', 'F.2.1')]
    def find(s, n, t):
        for r in db.findall('relationship'):
            if r.findtext('sourceId') == s and rname[r.findtext('schemaRelationId')] == n and r.findtext('targetId') == t: return r
    for (s, n, t), (s2, n2, t2) in (((g, 'decomposes', f2), (f21, 'decomposes', f2)), ((f2, 'decomposed by', g), (f2, 'decomposed by', f21))):
        a, b = find(s, n, t), find(s2, n2, t2)
        if a is not None and b is not None:
            db.remove(a); b.addprevious(a)
    log.append(('F.2.8', 'renumbered', 'F.2.0 (placed first in decomposition order)'))
g0 = byNum[('Action', 'F.2.0')]

# 2. Input/outputs not satisfied by any requirement: internal flows satisfy the leaf functional requirement of their producer
FRN = {'F.2.0': '3.3.1.8', 'F.2.1': '3.3.1.1', 'F.2.2': '3.3.1.2', 'F.2.3': '3.3.1.3', 'F.2.4': '3.3.1.4', 'F.2.5': '3.3.1.5', 'F.2.6': '3.3.1.6', 'F.2.7': '3.3.1.7'}
for r in list(db.findall('relationship')):
    if rname[r.findtext('schemaRelationId')] == 'generated by':
        io = ents[r.findtext('sourceId')]; fn = ents[r.findtext('targetId')]
        n = io.findtext('number') or ''
        if cname[io.findtext('schemaClassId')] == 'Input/Output' and n.startswith('IO.') and 12 <= int(n[3:]) <= 22:
            fnum = fn.findtext('number')
            if fnum in FRN: add(byNum[('Requirement', FRN[fnum])], 'satisfied by', r.findtext('sourceId'))

# 3. Actions that do not satisfy or trace to any requirement: external functions and the Metafunction
T = {'F.1': ['3.2.1', '3.2.2'], 'F.3': ['3.2.6', '3.2.7'], 'F.4': ['3.2.3', '3.2.4'], 'F.5': ['3.2.5'], 'F.6': ['3.2.8']}
for fn, reqs in T.items():
    for q in reqs: add(byNum[('Action', fn)], 'satisfies', byNum[('Requirement', q)])
meta = byName[('Action', 'Metafunction')]
add(meta, 'traced to', byNum[('Requirement', '3')])
# 4. Actions with no number
if not ents[meta].findtext('number'): setnum(meta, 'F.0')

tree.write(dst, encoding='UTF-8', xml_declaration=True, standalone=True)
for l in log: print(*l)
g = {e.findtext('globalId') for e in db.findall('entity')}
print('dangling', sum(1 for r in db.findall('relationship') if r.findtext('sourceId') not in g or r.findtext('targetId') not in g))
