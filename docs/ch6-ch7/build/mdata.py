def verify(xml_path):
    """Check LxFLOW against the XML (before the two trace edits)."""
    from lxml import etree
    r = etree.parse(xml_path).getroot()
    sch = r.find("schema")
    rel = {c.get("id"): c.findtext("name") for c in sch.iter("schemaRelation")}
    db = r.find("database")
    ent = {e.findtext("globalId"): (e.findtext("number") or e.findtext("name")) for e in db.findall("entity")}
    gen, rec = defaultdict(set), defaultdict(set)
    for x in db.findall("relationship"):
        n = rel[x.findtext("schemaRelationId")]
        s, t = ent[x.findtext("sourceId")], ent[x.findtext("targetId")]
        if n == "generated by":
            gen[s].add(t)
        elif n == "received by":
            rec[s].add(t)
    problems = []
    for io, (srcs, dests) in L1FLOW.items():
        if io in ("IO.1", "IO.2", "IO.3", "IO.4", "IO.5", "IO.6", "IO.7", "IO.8", "IO.9", "IO.10", "IO.11"):
            exp_gen = {s for s in srcs if s != "ENV"}
            exp_rec = {d for d, _ in dests if d != "ENV"}
            m_src, m_dst, _ = META[io]
            # first-level view: ENV side is the top-level function (checked against the Metafunction)
            if "ENV" in srcs:
                exp_gen = {m_src}
            if any(d == "ENV" for d, _ in dests):
                exp_rec = {m_dst} | exp_rec
            # the model keeps both the F.2 and the first-level links, so compare the first-level part only
            got_gen, got_rec = gen[io], rec[io]
            exp_gen_fl = {s for s in srcs if s != "ENV"}
            exp_rec_fl = {d for d, _ in dests if d != "ENV"}
        else:
            got_gen, got_rec = gen[io], rec[io]
            exp_gen_fl = {s for s in srcs}
            exp_rec_fl = {d for d, _ in dests}
        for fix, (fio, ff) in CHANGES.items():
            if fio == io:
                exp_gen_fl -= {ff} if fix == "fix1" else set()
                exp_rec_fl -= {ff} if fix == "fix2" else set()
        l1g = {x for x in got_gen if x.startswith("F.2.")}
        l1r = {x for x in got_rec if x.startswith("F.2.")}
        if l1g != exp_gen_fl:
            problems.append((io, "generated by", sorted(l1g), sorted(exp_gen_fl)))
        if l1r != exp_rec_fl:
            problems.append((io, "received by", sorted(l1r), sorted(exp_rec_fl)))
    return problems


