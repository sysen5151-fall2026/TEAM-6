class Model:
    def __init__(self, path):
        self.tree = ET.parse(path)
        self.root = self.tree.getroot()
        self.db = self.root.find("database")
        schema = self.root.find("schema")
        self.cls_name = {c.get("id"): c.findtext("name") for c in schema if c.tag == "schemaClass"}
        self.prop_name = {}
        for c in schema:
            if c.tag == "schemaClass":
                for p in c.findall("schemaProperty"):
                    self.prop_name[p.get("id")] = p.findtext("name")
        self.by_gid = {e.findtext("globalId"): e for e in self.db.findall("entity")}
        self.rel_ids = {}  # (source class, relation name, target class) -> schemaRelationId
        rel_name = {c.get("id"): c.findtext("name") for c in schema if c.tag == "schemaRelation"}
        for r in self.db.findall("relationship"):
            s, t = self.by_gid[r.findtext("sourceId")], self.by_gid[r.findtext("targetId")]
            key = (self.cls(s), rel_name[r.findtext("schemaRelationId")], self.cls(t))
            self.rel_ids.setdefault(key, r.findtext("schemaRelationId"))
        self.next_id = max(int(e.get("id")) for e in self.db.findall("entity")) + 1
        self.used_gids = set(self.by_gid)
        self.rng = random.Random(1009)  # fixed seed: the same script always gives the same ids
        self.now = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.000Z")
        self.first_relationship = self.db.find("relationship")
        self.new = {}  # key -> new entity element

    def cls(self, e):
        return self.cls_name[e.findtext("schemaClassId")]

    def find(self, number, cls=None, name=None):
        hits = [
            e for e in self.db.findall("entity")
            if (e.findtext("number") or "") == number
            and (cls is None or self.cls(e) == cls)
            and (name is None or e.findtext("name") == name)
        ]
        if len(hits) != 1:
            raise SystemExit(f"expected exactly one entity {cls or ''} {number!r} {name or ''}, found {len(hits)}")
        return hits[0]

    def ref(self, key):
        """An entity by the key it was created with, else by its number."""
        return self.new[key] if key in self.new else self.find(key)

    def gid(self):
        while True:
            g = "I_%s_%s" % (
                "".join(self.rng.choices(string.ascii_uppercase + string.digits, k=13)),
                "".join(self.rng.choices(string.ascii_uppercase + string.digits, k=14)),
            )
            if g not in self.used_gids:
                self.used_gids.add(g)
                return g

    def _set_attr(self, entity, prop, value):
        for a in entity:
            if a.tag.endswith("Attribute") and self.prop_name.get(a.get("schemaPropertyId")) == prop:
                for child in a:
                    if child.tag in ("value", "doubleValue", "booleanValue"):
                        child.text = str(value)
                        return
        raise SystemExit(f"property {prop!r} not found on the template of {entity.findtext('name')!r}")

    def add(self, key, template, number, name, description, attrs=None, label_from=None):
        e = copy.deepcopy(template)
        e.set("id", str(self.next_id))
        self.next_id += 1
        e.find("name").text = name
        e.find("description").text = description
        e.find("number").text = number
        e.find("globalId").text = self.gid()
        e.find("createdOn").text = e.find("modifiedOn").text = self.now
        for prop, value in (attrs or {}).items():
            self._set_attr(e, prop, value)
        if label_from is not None and label_from.find("labelId") is not None:
            e.find("labelId").text = label_from.findtext("labelId")
        self.new[key] = e
        self.db.insert(len(self.db.findall("entity")), e)  # entities stay ahead of relationships
        return e

    def _write_rel(self, a, name, b):
        key = (self.cls(a), name, self.cls(b))
        if key not in self.rel_ids:
            raise SystemExit(f"no existing relation of kind {key}; cannot invent its schema id")
        r = ET.SubElement(self.db, "relationship")
        ET.SubElement(r, "sourceId").text = a.findtext("globalId")
        ET.SubElement(r, "schemaRelationId").text = self.rel_ids[key]
        ET.SubElement(r, "targetId").text = b.findtext("globalId")

    def link(self, a, name, b):
        a, b = self.ref(a) if isinstance(a, str) else a, self.ref(b) if isinstance(b, str) else b
        self._write_rel(a, name, b)
        self._write_rel(b, INVERSE[name], a)


