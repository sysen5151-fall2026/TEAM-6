"""Structure checks on the Innoslate export 11.0 (10.9 plus the bus, vehicles, accounts and place suggestions).

These check the file, not Innoslate: the export has not been imported yet, so Innoslate's own
Intelligence report is still needed. Run:  python -m unittest discover -s tests -t .
"""

import os
import unittest
import xml.etree.ElementTree as ET

from tests.test_model_10_9 import Model

MODEL_DIR = os.path.join(os.path.dirname(__file__), "..", "docs", "model")
OLD = os.path.join(MODEL_DIR, "EcoCommute_10.9_web_flow.xml")
NEW = os.path.join(MODEL_DIR, "EcoCommute_11.0_accounts_transit.xml")

NEW_NEEDS = {"1.1.12", "1.1.13", "1.1.14", "1.3.5"}
NEW_STAKEHOLDER = {"2.1.15", "2.1.16", "2.1.17", "2.1.18", "2.3.8"}
NEW_SYSTEM = {"3.1.1.11", "3.1.1.12", "3.1.1.13", "3.1.1.14", "3.1.2.8", "3.1.2.9", "3.2.11",
              "3.3.1.13", "3.3.1.14", "3.3.1.15", "3.3.1.16", "3.3.1.17",
              "3.4.5.5", "3.4.5.6", "3.4.5.7", "3.4.6.3"}
NEW_WEB_ACTIONS = {"UC.3.12", "UC.3.13", "UC.3.14", "UC.3.15"}
NOT_RECEIVED = {"Place Suggestions", "Bus Schedule"}  # no step receives them
NEW_ACCOUNT_ACTIONS = {"UC.4"} | {f"UC.4.{i}" for i in range(1, 6)}
NEW_RISKS = {"TR.13", "TR.14", "TR.15"}
NEW_IO = {"Bus Schedule", "Trip Options", "Place Suggestions", "Account Details", "Signed-in Session"}
CHANGED_DESCRIPTIONS = {"2.1.11", "3.3.1.9"}  # they still said the bus time is typed


class TestModel110(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.old, cls.new = Model(OLD), Model(NEW)

    def added(self):
        return {gid: e for gid, e in self.new.by_gid.items() if gid not in self.old.by_gid}

    def test_nothing_from_10_9_was_removed_and_only_two_descriptions_changed(self):
        changed = set()
        for gid, entity in self.old.by_gid.items():
            self.assertIn(gid, self.new.by_gid)
            for tag in ("name", "number", "schemaClassId"):
                self.assertEqual(entity.findtext(tag), self.new.by_gid[gid].findtext(tag), (gid, tag))
            if entity.findtext("description") != self.new.by_gid[gid].findtext("description"):
                changed.add((entity.findtext("number") or "").strip())
        self.assertEqual(changed, CHANGED_DESCRIPTIONS)
        self.assertLessEqual(set(self.old.relationships), set(self.new.relationships))

    def test_the_changed_descriptions_no_longer_say_the_bus_time_is_typed(self):
        for n in CHANGED_DESCRIPTIONS:
            text = self.new.one(n, "Requirement").findtext("description")
            self.assertNotIn("enters a door-to-door time", text)
            self.assertNotIn("when a time is entered", text)
            self.assertIn("bus", text)

    def test_exactly_the_planned_elements_were_added(self):
        names = {(e.findtext("number") or "").strip() or e.findtext("name") for e in self.added().values()}
        expected = (NEW_NEEDS | NEW_STAKEHOLDER | NEW_SYSTEM | NEW_WEB_ACTIONS | NEW_ACCOUNT_ACTIONS
                    | NEW_RISKS | NEW_IO | {"X.7", "Transit schedule"})
        self.assertEqual(names, expected)

    def test_ids_are_unique(self):
        ids = [e.get("id") for e in self.new.entities]
        gids = [e.findtext("globalId") for e in self.new.entities]
        self.assertEqual(len(ids), len(set(ids)))
        self.assertEqual(len(gids), len(set(gids)))

    def test_every_relationship_has_both_ends_and_an_inverse(self):
        inverse = {"satisfies": "satisfied by", "traced to": "traced from", "decomposes": "decomposed by",
                   "performs": "performed by", "receives": "received by", "generates": "generated by",
                   "connects to": "connected by", "transfers": "transferred by", "relates": "related to",
                   "source of": "sourced by"}
        inverse.update({v: k for k, v in list(inverse.items())})
        for s, name, t in self.new.relationships:
            self.assertIn(s, self.new.by_gid)
            self.assertIn(t, self.new.by_gid)
            self.assertIn(s, self.new.out[(t, inverse[name])], (name, s, t))

    def test_each_new_need_is_traced_to_a_stakeholder_and_a_requirement(self):
        for n in NEW_NEEDS:
            self.assertTrue({"SH.1", "SH.3"} & self.new.targets(n, "traced to"), n)
            self.assertTrue(any(t.startswith("2.") for t in self.new.targets(n, "traced to")), n)

    def test_each_new_stakeholder_requirement_has_a_need_a_parent_and_something_that_satisfies_it(self):
        for n in NEW_STAKEHOLDER:
            self.assertTrue(any(t.startswith("1.") for t in self.new.targets(n, "traced from")), n)
            self.assertTrue(any(t.startswith("UC.") for t in self.new.targets(n, "satisfied by")), n)
            self.assertTrue(self.new.targets(n, "decomposes"), n)
            self.assertTrue(any(t.startswith("3.") for t in self.new.targets(n, "traced to")), n)

    def test_each_new_system_requirement_traces_to_a_stakeholder_requirement_and_is_satisfied(self):
        for n in NEW_SYSTEM:
            self.assertTrue(any(t.startswith("2.") for t in self.new.targets(n, "traced from")), n)
            self.assertTrue(self.new.targets(n, "satisfied by"), n)
            self.assertTrue(self.new.targets(n, "decomposes"), n)

    def test_use_case_3_gained_four_steps_and_use_case_4_has_five(self):
        steps3 = {f"UC.3.{i}" for i in range(1, 16)}
        self.assertEqual(self.new.targets("UC.3", "decomposed by"), steps3)
        self.assertEqual(self.new.targets("UC.4", "decomposed by"), {f"UC.4.{i}" for i in range(1, 6)})
        self.assertIn("UC.0", self.new.targets("UC.4", "decomposes"))
        for n in NEW_WEB_ACTIONS | (NEW_ACCOUNT_ACTIONS - {"UC.4"}):
            self.assertTrue(self.new.targets(n, "performed by"), n)
        self.assertEqual(self.new.targets("UC.3.13", "performed by"), {"C.2"})
        self.assertEqual(self.new.targets("UC.3.14", "performed by"), {"C.3"})
        self.assertEqual(self.new.targets("UC.3.15", "performed by"), {"X.7"})

    def test_every_new_action_satisfies_a_requirement(self):  # Intelligence error found on importing 10.9
        for n in NEW_WEB_ACTIONS | NEW_ACCOUNT_ACTIONS:
            self.assertTrue(self.new.targets(n, "satisfies"), n)

    def test_no_new_action_receives_a_flow_from_a_later_action_in_either_order(self):
        # Intelligence reported "prior action is dependent on the later action" on 10.9 for plain string order.
        natural = lambda n: [int(p) for p in n.split(".")[2:]]
        actions = NEW_WEB_ACTIONS | (NEW_ACCOUNT_ACTIONS - {"UC.4"})
        for order in (natural, str):
            for n in actions:
                for io in self.new.out[(self.new.gid(n, "Action"), "receives")]:
                    for producer in self.new.out[(io, "generated by")]:
                        p = (self.new.by_gid[producer].findtext("number") or "").strip()
                        if p.startswith(("UC.3.", "UC.4.")):
                            self.assertLess(order(p), order(n), (n, p))

    def test_every_new_input_output_is_generated_and_all_but_two_are_received(self):
        for name in NEW_IO:
            gid = [e for e in self.new.entities if e.findtext("name") == name][0].findtext("globalId")
            self.assertTrue(self.new.out[(gid, "generated by")], name)
            if name not in NOT_RECEIVED:
                self.assertTrue(self.new.out[(gid, "received by")], name)

    def test_no_two_entities_share_a_simulation_control_structure_id(self):
        # Copies of UC.1.10 all carried its two ids; fresh imports of such files gave a false "prior action" error.
        seen = {}
        for e in self.new.entities:
            for x in e.iter():
                if x is not e and x.get("id") and "-" in x.get("id"):
                    self.assertNotIn(x.get("id"), seen, (e.findtext("number"), seen.get(x.get("id"))))
                    seen[x.get("id")] = e.findtext("number")

    def test_parent_timelines_list_every_step_in_number_order(self):
        # Innoslate's "prior action" check reads the timeline in the parent's simulation data.
        for parent, count in (("UC.3", 15), ("UC.4", 5)):
            sim = self.new.one(parent, "Action").find("simulationData")
            chain, node = [], sim.find("controlStructure")
            while node is not None:
                node = node.find("successorStructure")
                if node is not None and node.findtext("entityGlobalId"):
                    chain.append((self.new.by_gid[node.findtext("entityGlobalId")].findtext("number")))
            self.assertEqual(chain, [f"{parent}.{i}" for i in range(1, count + 1)], parent)

    def test_flows_follow_the_timeline(self):
        for parent in ("UC.3", "UC.4"):
            order = {f"{parent}.{i}": i for i in range(1, 16)}
            for n in order:
                if n not in self.new.by_number:
                    continue
                for io in self.new.out[(self.new.gid(n, "Action"), "receives")]:
                    for producer in self.new.out[(io, "generated by")]:
                        p = (self.new.by_gid[producer].findtext("number") or "").strip()
                        if p in order:
                            self.assertLess(order[p], order[n], (n, p))

    def test_every_new_input_output_satisfies_a_requirement(self):  # Intelligence error found on importing 11.0
        for name in NEW_IO:
            gid = [e for e in self.new.entities if e.findtext("name") == name][0].findtext("globalId")
            self.assertTrue(self.new.out[(gid, "satisfies")], name)

    def test_flows_join_only_neighbouring_steps(self):
        # 10.9 passed Intelligence with such flows only; 11.0 with skipped steps gave "prior action is dependent".
        def last(n):
            return int(n.split(".")[-1])
        for n in NEW_WEB_ACTIONS | (NEW_ACCOUNT_ACTIONS - {"UC.4"}):
            for io in self.new.out[(self.new.gid(n, "Action"), "receives")]:
                for producer in self.new.out[(io, "generated by")]:
                    p = (self.new.by_gid[producer].findtext("number") or "").strip()
                    if p.startswith(("UC.3.", "UC.4.")):
                        self.assertEqual(last(n) - last(p), 1, (n, p))

    def test_new_requirements_are_drafts_and_make_no_quality_claim(self):
        for n in NEW_STAKEHOLDER | NEW_SYSTEM:
            text = ET.tostring(self.new.one(n, "Requirement"), encoding="unicode")
            self.assertIn("Draft", text)
            self.assertNotIn("<booleanValue>true</booleanValue>", text, n)


if __name__ == "__main__":
    unittest.main()
