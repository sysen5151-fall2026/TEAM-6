"""Structure checks on the Innoslate export 10.9 (10.8 plus the web-flow elements).

These check the file, not Innoslate: the export has not been imported yet, so Innoslate's own
Intelligence report is still needed. Run:  python -m unittest discover -s tests -t .
"""

import os
import unittest
import xml.etree.ElementTree as ET
from collections import defaultdict

MODEL_DIR = os.path.join(os.path.dirname(__file__), "..", "docs", "model")
OLD = os.path.join(MODEL_DIR, "EcoCommute_10.8_C6-C7_trace_update.xml")
NEW = os.path.join(MODEL_DIR, "EcoCommute_10.9_web_flow.xml")

NEW_NEEDS = {"1.1.9", "1.1.10", "1.1.11", "1.2.4"}
NEW_STAKEHOLDER = {"2.1.11", "2.1.12", "2.1.13", "2.1.14", "2.2.5"}
NEW_SYSTEM = {"3.1.1.8", "3.1.1.9", "3.1.1.10", "3.1.2.5", "3.1.2.6", "3.1.2.7", "3.2.9", "3.2.10",
              "3.3.1.9", "3.3.1.10", "3.3.1.11", "3.3.1.12", "3.4.5.4", "3.4.6.2"}
NEW_USE_CASE = {"UC.3"} | {f"UC.3.{i}" for i in range(1, 12)}
NEW_RISKS = {"TR.10", "TR.11", "TR.12"}


class Model:
    def __init__(self, path):
        root = ET.parse(path).getroot()
        schema, db = root.find("schema"), root.find("database")
        self.cls = {c.get("id"): c.findtext("name") for c in schema if c.tag == "schemaClass"}
        self.rel = {c.get("id"): c.findtext("name") for c in schema if c.tag == "schemaRelation"}
        self.entities = db.findall("entity")
        self.by_gid = {e.findtext("globalId"): e for e in self.entities}
        self.relationships = [
            (r.findtext("sourceId"), self.rel[r.findtext("schemaRelationId")], r.findtext("targetId"))
            for r in db.findall("relationship")
        ]
        self.out = defaultdict(set)  # (gid, relation name) -> {target gids}
        for s, name, t in self.relationships:
            self.out[(s, name)].add(t)
        self.by_number = defaultdict(list)
        for e in self.entities:
            self.by_number[(e.findtext("number") or "").strip()].append(e)

    def one(self, number, cls=None):
        hits = [e for e in self.by_number[number] if cls is None or self.cls[e.findtext("schemaClassId")] == cls]
        assert len(hits) == 1, (number, cls, len(hits))
        return hits[0]

    def gid(self, number, cls=None):
        return self.one(number, cls).findtext("globalId")

    def targets(self, number, relation, cls=None):
        return {
            (self.by_gid[t].findtext("number") or "").strip()
            for t in self.out[(self.gid(number, cls), relation)]
        }


class TestModel109(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.old, cls.new = Model(OLD), Model(NEW)

    def test_nothing_from_10_8_was_changed_or_removed(self):
        for gid, entity in self.old.by_gid.items():
            self.assertIn(gid, self.new.by_gid)
            for tag in ("name", "number", "description", "schemaClassId"):
                self.assertEqual(entity.findtext(tag), self.new.by_gid[gid].findtext(tag), (gid, tag))
        self.assertLessEqual(set(self.old.relationships), set(self.new.relationships))

    def test_exactly_the_planned_elements_were_added(self):
        added = {
            (e.findtext("number") or "").strip() or e.findtext("name")
            for gid, e in self.new.by_gid.items() if gid not in self.old.by_gid
        }
        io_and_conduits = {"Trip Places", "Route Request", "Route Options", "Mode Comparison", "Mode Choice",
                           "Trip Result and Progress", "Route request", "Route response"}
        expected = NEW_NEEDS | NEW_STAKEHOLDER | NEW_SYSTEM | NEW_USE_CASE | NEW_RISKS | {"X.6"} | io_and_conduits
        self.assertEqual(added, expected)

    def test_ids_are_unique(self):
        ids = [e.get("id") for e in self.new.entities]
        gids = [e.findtext("globalId") for e in self.new.entities]
        self.assertEqual(len(ids), len(set(ids)))
        self.assertEqual(len(gids), len(set(gids)))

    def test_every_relationship_has_both_ends_and_an_inverse(self):
        inverse = {"satisfies": "satisfied by", "traced to": "traced from", "decomposes": "decomposed by",
                   "performs": "performed by", "receives": "received by", "generates": "generated by",
                   "connects to": "connected by", "transfers": "transferred by", "relates": "related to",
                   "source of": "sourced by"}
        inverse.update({v: k for k, v in list(inverse.items())})
        for s, name, t in self.new.relationships:
            self.assertIn(s, self.new.by_gid)
            self.assertIn(t, self.new.by_gid)
            self.assertIn(s, self.new.out[(t, inverse[name])], (name, s, t))

    def test_each_new_need_is_traced_to_a_stakeholder_and_a_requirement(self):
        for n in NEW_NEEDS:
            self.assertTrue({"SH.1", "SH.2"} & self.new.targets(n, "traced to"), n)
            self.assertTrue(any(t.startswith("2.") for t in self.new.targets(n, "traced to")), n)

    def test_each_new_stakeholder_requirement_has_a_need_a_parent_and_something_that_satisfies_it(self):
        for n in NEW_STAKEHOLDER:
            self.assertTrue(any(t.startswith("1.") for t in self.new.targets(n, "traced from")), n)
            self.assertTrue(any(t.startswith("UC.3") for t in self.new.targets(n, "satisfied by")), n)
            self.assertTrue(self.new.targets(n, "decomposes"), n)
            self.assertTrue(any(t.startswith("3.") for t in self.new.targets(n, "traced to")), n)

    def test_each_new_system_requirement_traces_to_a_stakeholder_requirement_and_is_satisfied(self):
        for n in NEW_SYSTEM:
            self.assertTrue(any(t.startswith("2.") for t in self.new.targets(n, "traced from")), n)
            self.assertTrue(self.new.targets(n, "satisfied by"), n)
            self.assertTrue(self.new.targets(n, "decomposes"), n)

    def test_use_case_3_is_decomposed_performed_and_connected(self):
        steps = NEW_USE_CASE - {"UC.3"}
        self.assertEqual(self.new.targets("UC.3", "decomposed by"), steps)
        self.assertIn("UC.0", self.new.targets("UC.3", "decomposes"))
        for n in steps:
            self.assertEqual(self.new.targets(n, "decomposes"), {"UC.3"}, n)
            self.assertTrue(self.new.targets(n, "performed by"), n)
        self.assertEqual(self.new.targets("UC.3.4", "performed by"), {"X.6"})
        self.assertEqual(self.new.targets("UC.3.3", "performed by"), {"C.3"})

    def test_every_use_case_3_action_satisfies_a_requirement(self):  # Intelligence error found on import
        for n in NEW_USE_CASE:
            self.assertTrue(self.new.targets(n, "satisfies"), n)

    def test_no_use_case_3_action_receives_a_flow_from_a_later_action_in_either_order(self):
        # Intelligence reported "prior action is dependent on the later action" when UC.3.10 received a
        # flow from UC.3.8: plain string order puts UC.3.10 before UC.3.8. Both orders must be consistent.
        natural = lambda n: int(n.split(".")[-1])
        for order in (natural, str):
            for n in NEW_USE_CASE - {"UC.3"}:
                for io in self.new.out[(self.new.gid(n, "Action"), "receives")]:
                    for producer in self.new.out[(io, "generated by")]:
                        p = (self.new.by_gid[producer].findtext("number") or "").strip()
                        if p in NEW_USE_CASE:
                            self.assertLess(order(p), order(n), (n, p))

    def test_every_new_input_output_is_generated_and_received(self):
        for name in ("Trip Places", "Route Request", "Route Options", "Mode Comparison", "Mode Choice"):
            gid = [e for e in self.new.entities if e.findtext("name") == name][0].findtext("globalId")
            self.assertTrue(self.new.out[(gid, "generated by")], name)
            self.assertTrue(self.new.out[(gid, "received by")], name)

    def test_new_requirements_are_drafts_and_make_no_quality_claim(self):
        for n in NEW_STAKEHOLDER | NEW_SYSTEM:
            text = ET.tostring(self.new.one(n, "Requirement"), encoding="unicode")
            self.assertIn("Draft", text)
            self.assertNotIn("<booleanValue>true</booleanValue>", text, n)


if __name__ == "__main__":
    unittest.main()
